import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { CTF_ID, SECOND_ID, installCtfApi, openCtfMenu } from './ctf-fixtures';

const screenshots = '../docs/tasks/ctf-t6-screenshots';

test('结论、归档与外部目标分开展示，桌面及窄屏保留历史', async ({ page }) => {
  const mock = await installCtfApi(page);
  mock.finish('finished');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/tasks/${CTF_ID}`);
  await openCtfMenu(page);
  await page.getByRole('button', { name: '收尾与恢复' }).click();
  const recovery = page.getByRole('region', { name: '收尾与恢复' });
  await expect(recovery.getByRole('heading', { name: '本轮结论' })).toBeVisible();
  await expect(recovery).toContainText('模拟 Web 题仍需验证');
  await expect(recovery).toContainText('本机清理已完成');
  await expect(recovery).toContainText('不代表外部目标已关闭');
  await expect(recovery.getByRole('link', { name: '查看报告' })).toHaveAttribute('href', `/api/tasks/${CTF_ID}/report?run=1`);
  await expect(recovery.getByRole('link', { name: '下载归档' })).toHaveAttribute('href', `/api/tasks/${CTF_ID}/workspace?run=1`);
  await mkdir(screenshots, { recursive: true });
  await recovery.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${screenshots}/finished-recovery-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await recovery.getByRole('heading', { name: '本机归档与清理' }).scrollIntoViewIfNeeded();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: `${screenshots}/finished-recovery-mobile.png` });
  await recovery.getByRole('button', { name: '关闭', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.getByRole('button', { name: 'Agent：历史队友' }).click();
  await expect(page.getByRole('region', { name: '历史队友 会话' })).toContainText('member-3 的历史工作记录');
  expect(mock.resumes).toEqual([]);
  expect(mock.deletions).toEqual([]);
  expect(mock.unexpected).toEqual([]);
});

test('归档未完成时阻止续跑，保存完成后显式申请且双击与重试复用ID', async ({ page }) => {
  const mock = await installCtfApi(page);
  mock.finish('failed', false);
  await page.goto(`/tasks/${CTF_ID}`);
  await openCtfMenu(page);
  await page.getByRole('button', { name: '收尾与恢复' }).click();
  const recovery = page.getByRole('region', { name: '收尾与恢复' });
  await expect(recovery).toContainText('系统执行失败');
  await expect(recovery).toContainText('失败诊断');
  await expect(recovery).toContainText('00000000-0000-4000-8000-000000000001');
  await expect(recovery).toContainText('RuntimeError');
  await expect(recovery).toContainText('本机清理尚未完成');
  await recovery.getByRole('button', { name: '续跑任务' }).click();
  const dialog = page.getByRole('dialog', { name: '续跑 CTF 任务' });
  await expect(dialog.getByRole('button', { name: '确认续跑' })).toBeDisabled();
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  expect(mock.resumes).toEqual([]);
  await recovery.getByRole('button', { name: '关闭', exact: true }).click();
  mock.finish('failed', true);
  await openCtfMenu(page);
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  if (await page.getByRole('button', { name: '收尾与恢复' }).count() === 0) await openCtfMenu(page);
  await page.getByRole('button', { name: '收尾与恢复' }).click();
  const refreshedRecovery = page.getByRole('region', { name: '收尾与恢复' });
  await expect(refreshedRecovery).toContainText('本机清理已完成');
  await refreshedRecovery.getByRole('button', { name: '续跑任务' }).click();
  await dialog.getByLabel('追加金额（CNY）').fill('2.5');
  await dialog.getByLabel('追加运行分钟').fill('30');
  mock.failResume(); mock.holdResume();
  await dialog.getByRole('button', { name: '确认续跑' }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); });
  await expect.poll(() => mock.resumes.length).toBe(1);
  await expect(dialog.getByRole('button', { name: '正在续跑…' })).toBeDisabled();
  mock.releaseResume();
  await expect(dialog.getByRole('alert')).toContainText('模拟续跑暂时失败');
  await expect(dialog.getByLabel('追加金额（CNY）')).toHaveValue('2.5');
  await expect(dialog.getByLabel('追加运行分钟')).toHaveValue('30');
  await mkdir(screenshots, { recursive: true });
  await page.screenshot({ path: `${screenshots}/resume-failure-retry.png` });
  await dialog.getByRole('button', { name: '确认续跑' }).click();
  await expect(dialog).not.toBeVisible();
  expect(mock.resumes).toHaveLength(2);
  expect(mock.resumes[0]).toEqual(mock.resumes[1]);
  expect(mock.resumes[0]).toMatchObject({ task_id: CTF_ID, additional_cost: '2.5', additional_minutes: 30, refresh_tools: false });
  expect(mock.task.run_number).toBe(2);
  expect(mock.members.find((member) => member.id === 'member-2')?.lifecycle).toBe('stopped');
  expect(mock.members.find((member) => member.id === 'member-3')?.lifecycle).toBe('removed');
  expect(mock.task.runs[0].report_uri).toBe(`reports/${CTF_ID}/run-1.md`);
  expect(mock.secondTask.run_number).toBe(1);
  expect(mock.unexpected).toEqual([]);
});

test('离开正在续跑的任务后，迟到响应不会改变另一任务', async ({ page }) => {
  const mock = await installCtfApi(page);
  mock.finish('stopped');
  await page.goto('/tasks');
  await page.getByRole('link', { name: '查看任务：模拟验收 · 团队协作' }).click();
  await openCtfMenu(page);
  await page.getByRole('button', { name: '收尾与恢复' }).click();
  await page.getByRole('button', { name: '续跑任务', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '续跑 CTF 任务' });
  await dialog.getByLabel('追加金额（CNY）').fill('1');
  await dialog.getByLabel('追加运行分钟').fill('10');
  mock.holdResume();
  await dialog.getByRole('button', { name: '确认续跑' }).click();
  await expect.poll(() => mock.resumes.length).toBe(1);
  await page.goBack();
  await page.getByRole('link', { name: '查看任务：另一个模拟任务' }).click();
  await page.getByRole('button', { name: 'Agent：Lead' }).click();
  const next = page.getByRole('region', { name: 'Lead 会话' });
  await expect(next).toContainText('第二任务会话');
  await next.getByRole('textbox').fill('第二任务保留自己的草稿');
  mock.releaseResume();
  await expect.poll(() => mock.task.run_number).toBe(2);
  await expect(page).toHaveURL(new RegExp(SECOND_ID));
  await expect(next.getByRole('textbox')).toHaveValue('第二任务保留自己的草稿');
  expect(mock.secondTask.status).toBe('running');
  expect(mock.secondTask.run_number).toBe(1);
  expect(mock.resumes).toHaveLength(1);
  expect(mock.resumes[0].task_id).toBe(CTF_ID);
  expect(mock.unexpected).toEqual([]);
});

