test('发送中的任务切换不会把旧请求结果写入新会话', async ({ page }) => {
  const mock = await installCtfApi(page);
  await page.goto(`/tasks/${CTF_ID}`);
  mock.holdSend();
  await page.getByRole('button', { name: 'Agent：Lead' }).click();
  const chat = page.getByRole('complementary', { name: 'Lead 会话' });
  await chat.getByRole('textbox').fill('旧任务正在发送');
  await chat.getByRole('button', { name: '发送消息' }).click();
  await expect.poll(() => mock.sent.length).toBe(1);
  await page.getByRole('button', { name: '返回任务', exact: true }).click();
  await page.getByRole('link', { name: '查看任务：另一个模拟任务' }).click();
  await page.getByRole('button', { name: 'Agent：Lead' }).click();
  const next = page.getByRole('complementary', { name: 'Lead 会话' });
  await next.getByRole('textbox').fill('新任务尚未发送的草稿');
  mock.releaseSend();
  await expect(next).toContainText('第二任务会话');
  await expect(next.getByRole('textbox')).toHaveValue('新任务尚未发送的草稿');
  expect(mock.sent).toHaveLength(1);
  expect(mock.sent[0].task_id).toBe(CTF_ID);
  await expect(next).not.toContainText('旧任务正在发送');
  expect(mock.unexpected).toEqual([]);
});
