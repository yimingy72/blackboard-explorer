test('定向消息重复点击只发送一次，失败重试复用ID并保留内容', async ({ page }) => {
  const mock = await installCtfApi(page);
  await page.goto(`/tasks/${CTF_ID}`);
  await page.getByRole('button', { name: 'Agent：Web 分析员' }).click();
  const chat = page.getByRole('complementary', { name: 'Web 分析员 会话' });
  mock.holdSend();
  await chat.getByRole('textbox').fill('请继续核对失败条件');
  await chat.getByRole('button', { name: '发送消息' }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); });
  await expect.poll(() => mock.sent.length).toBe(1);
  expect(mock.sent[0].member).toBe('member-1');
  mock.releaseSend();
  await expect(chat.getByRole('textbox')).toHaveValue('');
  mock.failSend();
  await chat.getByRole('textbox').fill('失败后保留的消息');
  await chat.getByRole('button', { name: '发送消息' }).click();
  await expect(chat.getByRole('alert')).toContainText('消息内容已保留');
  await expect(chat.getByRole('textbox')).toHaveValue('失败后保留的消息');
  await chat.getByRole('button', { name: '重试发送' }).click();
  await expect(chat.getByRole('textbox')).toHaveValue('');
  expect(mock.sent[1].id).toBe(mock.sent[2].id);
  expect(mock.unexpected).toEqual([]);
});

