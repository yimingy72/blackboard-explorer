import { expect, test } from '@playwright/test';
import { CTF_ID, installCtfApi, openCtfMenu } from './ctf-fixtures';

test('合成 CTF 会话连续展示 provider 推理与工具，题目保留多候选和独立验证', async ({ page }) => {
  const mock = await installCtfApi(page);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/tasks/' + CTF_ID);
  await expect(page.getByRole('main', { name: 'CTF 团队协作画布' })).toContainText('认领');
  await expect(page.getByRole('complementary', { name: /^题目详情：| 会话$/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Agent：Web 分析员' }).click();
  const conversation = page.getByRole('complementary', { name: 'Web 分析员 会话' });
  await expect(conversation).toBeVisible();
  await expect(conversation.getByRole('tablist')).toHaveCount(0);
  await expect(conversation).toContainText('准备读取公开复现脚本');
  await expect(conversation).toContainText('脚本与失败条件已保存');
  const reasoning = conversation.getByRole('button', { name: '思考 · 模型返回', exact: true });
  await expect(conversation.getByText(/模拟 provider 原始 reasoning/)).toBeHidden();
  await reasoning.press('Enter');
  await expect(reasoning).toHaveAttribute('aria-expanded', 'true');
  await expect(conversation.getByText(/模拟 provider 原始 reasoning：先核对空输入/)).toBeVisible();
  await conversation.getByRole('button', { name: '思考摘要', exact: true }).press('Enter');
  await expect(conversation.getByText(/模拟 provider 摘要：检查编码边界/)).toBeVisible();
  const tool = conversation.getByRole('button', { name: /^read_artifact/ });
  await expect(tool).toContainText('已完成');
  await expect(tool).toHaveAttribute('aria-expanded', 'false');
  await tool.press('Enter');
  const toolContent = conversation.getByRole('region', { name: 'read_artifact 参数与结果', exact: true });
  await expect(toolContent.locator('pre').first()).toContainText('/workspace/shared/probe.py');
  const result = toolContent.locator('pre').last();
  await expect(result).toContainText('公开结果：空输入解码失败');
  await expect(conversation).not.toContainText('PRIVATE_');
  await tool.press('Enter');
  await expect(tool).toHaveAttribute('aria-expanded', 'false');
  await expect(result).toBeHidden();

  await page.getByRole('button', { name: 'Agent：Lead' }).click();
  await expect(page.getByRole('complementary', { name: 'Lead 会话' })).toContainText('已分派两道模拟题');
  await page.getByRole('button', { name: '任务：模拟 Web 题' }).click();
  const detail = page.getByRole('complementary', { name: /^题目详情：/ });
  await expect(detail.getByRole('tabpanel')).toContainText('模拟平台 · 未通过');
  await expect(detail.getByRole('button', { name: '人工确认', exact: true })).toHaveCount(0);
  await expect(detail.getByRole('button').filter({ hasText: '调整验证要求' })).toHaveCount(0);
  await expect(detail).toContainText('第二个候选，保留用于复核');
  await detail.getByRole('tab', { name: /记录/ }).click();
  const candidateRegion = detail.getByRole('region', { name: '候选答案与独立验证' });
  const candidates = candidateRegion.getByRole('button', { name: /^候选 \d+ ·/ });
  await expect(candidates).toHaveCount(2);
  await expect(candidates.first()).toHaveAttribute('aria-expanded', 'false');
  await expect(candidates.last()).toHaveAttribute('aria-expanded', 'true');
  await expect(candidateRegion.getByText('FLAG{mock-second}', { exact: true })).toBeVisible();
  await candidates.first().click();
  await expect(candidateRegion.getByText('FLAG{mock-first}', { exact: true })).toBeVisible();
  await expect(detail).toContainText('空输入导致解码失败');
  await expect(detail).toContainText('尚未确定填充规则');
  await detail.getByRole('button', { name: '关闭详情' }).click();
  await expect(page.getByRole('complementary', { name: /^题目详情：| 会话$/ })).toHaveCount(0);
  await openCtfMenu(page);
  await page.getByRole('menuitem', { name: '刷新', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '刷新', exact: true })).toBeHidden();
  await expect(page.getByRole('main', { name: 'CTF 团队协作画布' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  expect(mock.unexpected).toEqual([]);
});

test('历史人工验证保持只读可查，题目不提供人工验证或要求调整入口', async ({ page }) => {
  const mock = await installCtfApi(page);
  mock.records.push({ id: 'R-history', challenge_id: 'C1', author_id: 'user', kind: 'verification', body: '旧版保存的人工验证记录', created_version: 12, artifact_refs: [], verification: { source: 'user', status: 'accepted', summary: '用户历史确认依据保留', user_id: 'historical-reviewer' } });
  await page.goto(`/tasks/${CTF_ID}`);
  await page.getByRole('button', { name: '任务：模拟 Web 题' }).click();
  const detail = page.getByRole('complementary', { name: /^题目详情：/ });
  await expect(detail.getByRole('button', { name: '人工确认', exact: true })).toHaveCount(0);
  await expect(detail.getByRole('button').filter({ hasText: '调整验证要求' })).toHaveCount(0);
  await expect(detail.getByRole('textbox')).toHaveCount(0);
  await detail.getByRole('tab', { name: /记录/ }).click();
  await expect(detail).toContainText('旧版保存的人工验证记录');
  await expect(detail).toContainText('人工 · 已通过');
  await expect(detail).toContainText('用户历史确认依据保留');
  await expect(detail).toContainText('historical-reviewer');
  expect(mock.operations).toEqual([]);
  expect(mock.unexpected).toEqual([]);
});

test('finished、候选和模拟验收通过都不会冒充真实独立验证', async ({ page }) => {
  const mock = await installCtfApi(page);
  mock.finish('finished');
  mock.challenges[0].verification.status = 'accepted';
  await page.goto('/tasks/' + CTF_ID);
  await expect(page.getByText('已结束', { exact: true })).toBeVisible();
  await expect(page.getByText('1 候选待验', { exact: true })).toBeVisible();
  await expect(page.getByText(/\d+ 已验证/, { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '任务：模拟 Web 题' }).click();
  const detail = page.getByRole('complementary', { name: /^题目详情：/ });
  await expect(detail).toContainText('模拟平台 · 已通过');
  mock.challenges[0].verification = { source: 'platform', status: 'accepted', required: true, test_only: false };
  await detail.getByRole('button', { name: '关闭详情' }).click();
  await openCtfMenu(page);
  await page.getByRole('menuitem', { name: '刷新', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '刷新', exact: true })).toBeHidden();
  await expect(page.getByText('1 已验证', { exact: true })).toBeVisible();
  expect(mock.unexpected).toEqual([]);
});
